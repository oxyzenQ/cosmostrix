#
# ─────────────────────────────────────────────────────────────────────────────
# PLATFORM: UNIX-only (Linux, macOS, BSD).
#   Uses `git ls-files`, `cmp`, `mktemp`, `mapfile`, `grep -F`. Not for
#   Windows cmd.exe / PowerShell — use Git Bash or WSL on Windows.
# ─────────────────────────────────────────────────────────────────────────────
#
# Guarantees the "documentation disclaimer" note sits at the BOTTOM of
# every living git-tracked *.md file in the repo — the last content
# block, never mid-file and never under a header. The disclaimer warns
# readers that docs may contain stale data, hardcoded counts, or
# outdated references because maintainers update source code but may
# forget to sync docs. Source code is the single source of truth —
# cross-check before relying on any specific number, file path, or
# symbol name.
#
# PLACEMENT LAW (owner directive, zejtron night-dragon-2S lineage):
# the predecessor injector treated marker PRESENCE as the done
# verdict, so a block landed mid-file the moment later content was
# appended below it (the README footer, the A/B report verification
# footers, new doc sections) and stayed there forever. This port
# reads PLACEMENT as the verdict: any disclaimer block found anywhere
# other than the bottom is stripped from its position and re-appended
# as the file's final block, so one run normalizes every file and a
# second run changes no bytes.
#
#   - the marker line is `<!-- COSMOSTRIX-DISCLAIMER -->`, followed by
#     the single HTML comment that closes on the next `-->` line;
#   - a truncated legacy block (marker line with no closing `-->`)
#     is stripped the same way — everything from the marker to EOF;
#   - between the closing `-->` and EOF nothing but blank lines may
#     remain; one blank line separates the block from the body above.
#
# The NIGHT-docs-1 (2026-09-24) duplicate law is preserved: a
# hand-pasted UNMARKED copy of the block (no marker line) survives
# the normalize sweep, so the canonical header line is counted
# separately — more than one copy per file is a hard failure the
# injector refuses to paper over (hand cleanup required). Exactly
# one "Documentation Disclaimer" header line per file, marker or not.
#
# Excluded (the frozen-record and generated-artifact classes the gate
# must not demand edits in):
#   - CHANGELOG.md — the frozen release ledger;
#   - docs/archive/** — the frozen era records;
#   - benchmark/bench-labs/sweep_*.md — machine-generated by
#     `benchmark/benchmark.sh sweep` on every performance update.
#     They are data reports, not documentation; the maintenance-sync
#     warning the disclaimer carries does not apply, and requiring it
#     would break the gatekeeper on every sweep regeneration
#     (observed in CI run #79). License compliance is still enforced:
#     the generator emits the SPDX header into every sweep file, and
#     check-headers.sh verifies it.
#   - benchmark/bench-labs/BENCH_LABS.md is intentionally NOT
#     excluded — it is a hand-maintained index document and must keep
#     the disclaimer.
#
# Usage:
#   bash scripts/gates/inject-disclaimer.sh          # normalize (inject/relocate)
#   bash scripts/gates/inject-disclaimer.sh --check  # verify placement only
#
# Exit codes:
#   0 = every living .md carries the bottom block (or was normalized)
#   1 = --check mode found at least one file missing or misplaced
#   2 = usage error

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
CHECK_MODE=false

if [[ "${1:-}" == "--check" ]]; then
        CHECK_MODE=true
elif [[ $# -gt 0 ]]; then
        echo "usage: bash scripts/gates/inject-disclaimer.sh [--check]" >&2
        exit 2
fi

# The disclaimer marker — must match exactly for idempotency.
MARKER="<!-- COSMOSTRIX-DISCLAIMER -->"

# The canonical header line inside the block body. Counted separately
# from the marker so an unmarked hand-pasted copy still fails the
# duplicate law (NIGHT-docs-1).
HEADER_LINE="  Documentation Disclaimer — read before relying on any data point."

# Auto-generated benchmark artifacts excluded from the disclaimer
# check (sweep reports only; see the header note for the rationale).
EXCLUDE_PATTERN='^benchmark/bench-labs/sweep_[^/]*\.md$'

# The canonical block. The leading separator blank line is added at
# append time, so the heredoc carries the block proper only.
read -r -d '' BLOCK_TEXT <<'EOF' || true
<!-- COSMOSTRIX-DISCLAIMER -->
<!--
  Documentation Disclaimer — read before relying on any data point.

  This document may contain stale data, hardcoded counts, or outdated
  file paths and symbol names. Maintainers update source code but may
  forget to sync every doc — the project ships 80+ .md files and
  perfect sync is a known maintenance burden with diminishing returns.

  Source code (`src/**/*.rs`) is the single source of truth.
  Always cross-check against the actual `.rs` files before relying on
  any specific number (test count, LOC, FPS, ms timeout), file path,
  function name, or config key.

  If you find a discrepancy, please open a PR — the doc is wrong, not
  the source.
-->
EOF
mapfile -t BLOCK_LINES <<<"${BLOCK_TEXT}"

# Colors
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[0;33m'
NC='\033[0m'

CHECKED=0
OK_BOTTOM=0
INJECTED=0
RELOCATED=0
DUPLICATES=0
NOT_BOTTOM=0

TMPDIR="$(mktemp -d "${TMPDIR:-/tmp}/cosmostrix-discl.XXXXXX")"
trap 'rm -rf "${TMPDIR}"' EXIT

# normalize <file>: strip every disclaimer block from wherever it
# sits, then append the canonical block as the file's final block.
# Writes the candidate to stdout-bound temp file path; the caller
# compares bytes. Emits nothing.
normalize() {
        local file="$1"
        local -a lines=()
        mapfile -t lines <"${file}"

        local -a kept=()
        local i=0
        local n=${#lines[@]}
        while [ "${i}" -lt "${n}" ]; do
                local line="${lines[${i}]}"
                if [ "${line}" = "${MARKER}" ]; then
                        # swallow the one separator blank above the block
                        local top=$((${#kept[@]} - 1))
                        if [ "${top}" -ge 0 ] && [ -z "${kept[${top}]}" ]; then
                                kept=("${kept[@]:0:${top}}")
                        fi
                        # skip the block proper: to the closing --> line.
                        # A truncated legacy block (marker with no close)
                        # runs off the end here — stripped to EOF either way.
                        local j=$((i + 1))
                        while [ "${j}" -lt "${n}" ] && [ "${lines[${j}]}" != "-->" ]; do
                                j=$((j + 1))
                        done
                        i=$((j + 1))
                        continue
                fi
                kept+=("${line}")
                i=$((i + 1))
        done

        # strip the trailing blank runs the block left behind
        local last=$((${#kept[@]} - 1))
        while [ "${last}" -ge 0 ] && [ -z "${kept[${last}]}" ]; do
                last=$((last - 1))
        done
        kept=("${kept[@]:0:$((last + 1))}")

        local -a out=()
        if [ "${#kept[@]}" -gt 0 ]; then
                out=("${kept[@]}" "")
        fi
        out=("${out[@]}" "${BLOCK_LINES[@]}")

        local candidate="${TMPDIR}/normalized.md"
        printf '%s\n' "${out[@]}" >"${candidate}"
        printf '%s' "${candidate}"
}

process_file() {
        local rel="$1"
        local file="${REPO_ROOT}/${rel}"
        CHECKED=$((CHECKED + 1))

        # Duplicate law first: an unmarked hand-pasted copy of the
        # block does not ride a marker, so normalize cannot see it.
        # Count the canonical header line — exactly one copy per file.
        local headers
        headers=$(grep -cF "${HEADER_LINE}" "${file}" 2>/dev/null || true)
        if [[ "${headers:-0}" -gt 1 ]]; then
                echo -e "${RED}DUPLICATE disclaimer (${headers} copies, one unmarked): ${rel}${NC}"
                DUPLICATES=$((DUPLICATES + 1))
                NOT_BOTTOM=$((NOT_BOTTOM + 1))
                return 0
        fi

        local had_house=0
        if grep -Fq -- "${MARKER}" "${file}"; then
                had_house=1
        fi

        local candidate
        candidate="$(normalize "${file}")"
        local changed=1
        if cmp -s "${candidate}" "${file}"; then
                changed=0
        fi

        if [ "${CHECK_MODE}" = true ]; then
                if [ "${changed}" -eq 0 ]; then
                        OK_BOTTOM=$((OK_BOTTOM + 1))
                elif [ "${had_house}" -eq 1 ]; then
                        echo -e "${RED}MISPLACED block (not the bottom block): ${rel}${NC}"
                        NOT_BOTTOM=$((NOT_BOTTOM + 1))
                else
                        echo -e "${RED}MISSING disclaimer: ${rel}${NC}"
                        NOT_BOTTOM=$((NOT_BOTTOM + 1))
                fi
                return 0
        fi

        if [ "${changed}" -eq 0 ]; then
                OK_BOTTOM=$((OK_BOTTOM + 1))
                return 0
        fi
        cp "${candidate}" "${file}"
        if [ "${had_house}" -eq 1 ]; then
                echo "Relocated: ${rel} (block moved to the bottom)"
                RELOCATED=$((RELOCATED + 1))
        else
                echo "Injected: ${rel}"
                INJECTED=$((INJECTED + 1))
        fi
}

# Every tracked OR untracked-but-present .md (git ls-files
# --cached --others --exclude-standard respects .gitignore, so a
# freshly written .md fails the check BEFORE it can be committed —
# three CI incidents (runs #79, #96, and the docs-audit SPDX miss)
# were caused by the old --cached-only scan). The NUL shim is bash
# printf — awk cannot emit NUL bytes on mawk (the Ubuntu default).
while IFS= read -r -d '' rel; do
        process_file "${rel}"
done < <(
        cd "${REPO_ROOT}" &&
                git ls-files --cached --others --exclude-standard 2>/dev/null |
                grep -E '\.md$' |
                grep -Ev "${EXCLUDE_PATTERN}" |
                grep -Ev '^CHANGELOG\.md$' |
                grep -Ev '^docs/archive/' |
                while IFS= read -r line; do
                        printf '%s\0' "${line}"
                done
)

if ((DUPLICATES > 0)); then
        echo -e "${RED}FAIL: $DUPLICATES of $CHECKED .md files carry DUPLICATE disclaimer blocks${NC}"
        echo "Fix: delete every copy except the marker-adjacent one (bash scripts/gates/inject-disclaimer.sh --check)"
        exit 1
fi

if [ "${CHECK_MODE}" = true ]; then
        if [ "${NOT_BOTTOM}" -eq 0 ]; then
                echo -e "${GREEN}OK: ${CHECKED} .md files checked, every disclaimer sits at the bottom${NC}"
                exit 0
        fi
        echo -e "${RED}FAIL: ${NOT_BOTTOM} of ${CHECKED} .md files missing or misplaced${NC}"
        echo "Run: bash scripts/gates/inject-disclaimer.sh"
        exit 1
fi

echo ""
echo -e "${GREEN}Injected: ${INJECTED}  Relocated: ${RELOCATED}  Already-at-bottom: ${OK_BOTTOM}  Total: ${CHECKED}${NC}"
if [ "$((INJECTED + RELOCATED))" -gt 0 ]; then
        echo -e "${YELLOW}Review the git diff before staging.${NC}"
fi
exit 0
