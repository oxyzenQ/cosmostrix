"""Unsafe census pin (night-frontier-Z5c).

cosmostrix's unsafe surface is a closed, audited list: the OS-boundary
modules (clock, platform guards, watchdog, reclaim, sysstat, the
terminal/tty recovery ladder, the io_uring rejection record) carry a
fixed number of reviewed unsafe blocks, and EVERYTHING else in src/
must stay unsafe-free. The compiler now enforces the biggest half of
that law at build time (`#![forbid(unsafe_code)]` on the chroma and
crystal engines and the cosmic engine's render core - cloud/, frame,
runtime), but the compiler cannot see the REST of the tree: this gate
pins the full census so the surface can only change on purpose.

Counting rule (deterministic, the single source of truth for the pin
below): a line counts when the regex \bunsafe\b matches it AND the
line's stripped form does not start with `//` (plain and doc comments
- including every SAFETY: justification - are prose, not surface).
The pinned table is generated by this scanner itself; any drift in
either direction is a finding: growth adds unaudited unsafe, a shrink
means the pin is stale and must be consciously re-landed.

Exit codes: 0 = census matches the pin; 1 = drift (new unsafe, grown
count, shrunk count, or an unpinned file carrying unsafe); 2 = usage
or tree fault.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

UNSAFE_RE = re.compile(r"\bunsafe\b")

# The pinned census, generated by this scanner at the Z5c SHA.
# (file relative to src/ -> count of non-comment lines matching
# \bunsafe\b)
PINNED_CENSUS: dict[str, int] = {
    "bench/bench_perf.rs": 3,
    "central_control_power_dragon/reclaim_state.rs": 5,
    "clock/posix_time.rs": 8,
    "config/config_io.rs": 2,
    "cosmic_dragon_incubator/egg/io_uring_rejected.rs": 2,
    "diagnostics/alloc_trace.rs": 7,
    "diagnostics/info.rs": 1,
    "diagnostics/mod.rs": 1,
    "engine/cosmic_dragon_engine/terminal/terminal_tty.rs": 10,
    "interactive/watchdog.rs": 1,
    "platform/fork_guard.rs": 7,
    "platform/root_guard.rs": 1,
    "platform/termios_snapshot.rs": 6,
    "sysstat/cpustat.rs": 4,
    "sysstat/envstat.rs": 1,
    "sysstat/memstat.rs": 1,
    "sysstat/usagestat.rs": 1,
}


def census(src_root: Path) -> dict[str, int]:
    """Count non-comment lines carrying the unsafe keyword, per file."""
    found: dict[str, int] = {}
    for path in sorted(src_root.rglob("*.rs")):
        count = 0
        for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
            stripped = line.lstrip()
            if stripped.startswith("//"):
                continue
            if UNSAFE_RE.search(line):
                count += 1
        if count:
            found[str(path.relative_to(src_root)).replace("\\", "/")] = count
    return found


def main() -> int:
    repo_root = Path(__file__).resolve().parents[2]
    src_root = repo_root / "src"
    if not src_root.is_dir():
        print(f"unsafe-census: src tree not found at {src_root}", file=sys.stderr)
        return 2

    found = census(src_root)
    problems: list[str] = []

    for file, count in sorted(found.items()):
        pinned = PINNED_CENSUS.get(file)
        if pinned is None:
            problems.append(
                f"NEW unsafe surface: {file} carries {count} unsafe line(s) "
                "and is not in the pinned census - audit it, then (only if "
                "the owner approves the surface) add it to PINNED_CENSUS"
            )
        elif count > pinned:
            problems.append(
                f"GROWN unsafe surface: {file} went {pinned} -> {count} "
                "unsafe line(s) - unaudited growth is a finding"
            )
        elif count < pinned:
            problems.append(
                f"SHRUNK unsafe surface: {file} went {pinned} -> {count} - "
                "an improvement, but the pin is now stale: re-land "
                "PINNED_CENSUS in scripts/gates/unsafe-census.py"
            )

    for file, pinned in sorted(PINNED_CENSUS.items()):
        if file not in found:
            problems.append(
                f"VACATED unsafe surface: {file} now carries zero unsafe "
                "lines - retire it from PINNED_CENSUS (and consider "
                "widening the forbid(unsafe_code) scope)"
            )

    total = sum(found.values())
    pinned_total = sum(PINNED_CENSUS.values())
    if problems:
        print("unsafe-census: DRIFT from the pinned surface")
        for problem in problems:
            print(f"  - {problem}")
        print(
            f"unsafe-census: found {total} unsafe line(s) across "
            f"{len(found)} file(s), pin carries {pinned_total} across "
            f"{len(PINNED_CENSUS)}"
        )
        return 1

    print(
        f"unsafe-census: OK - {total} unsafe line(s) across "
        f"{len(found)} file(s), exactly the pinned surface; the engine "
        "render core is compiler-forbidden (forbid(unsafe_code))"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
