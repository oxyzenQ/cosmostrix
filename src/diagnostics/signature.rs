//! Provenance depth matrix — the embedded, masked build signature.
//!
//! night-signature-advanced-2 (supersedes the night-signature-1 draft):
//! the ownership claim "rezky_nightky (oxyzenQ) 2026" is embedded in the
//! binary in MASKED form and materializes to plaintext only at runtime,
//! on the `-V/--version` surface. The owner's threat model: a thief can
//! grep the artifact with `strings(1)`, `rg`, or a custom scanner, find
//! any plaintext wording, and patch it out. A plaintext-at-rest manifest
//! hands them the mark on a plate. Here the mark is present only as
//! opaque 64-bit integers:
//!
//!   D0  `MASKED_MANIFEST_WORDS` — the full Signature-line manifest,
//!       chunked into little-endian u64 words and XOR-masked with a
//!       splitmix64 stream keyed by `MANIFEST_SEED`. At rest: opaque
//!       integers in source and in `.rodata` — no printable run of four
//!       or more bytes exists anywhere in the masked words, so
//!       `strings ./cosmostrix | grep rezky` finds nothing.
//!
//!   D1  `MASKED_AUTHORS_WORDS` — the Copyright-line authors string,
//!       masked the same way under the independent `AUTHORS_SEED`. Two
//!       independent encodings of the same identity: patching one still
//!       leaves the other reconstructing the owner.
//!
//!   D2  `MANIFEST_FINGERPRINT` and `AUTHORS_FINGERPRINT` — FNV-1a
//!       64-bit digests over the CLEAR bytes, const-evaluated at compile
//!       time directly from the masked words (the plaintext never exists
//!       as a literal anywhere in this module — not even in const
//!       context). Recomputed at runtime from the same words; `-V`
//!       reports `status=verified` or `status=tampered` on its
//!       `Depth-matrix:` line.
//!
//! # The single-pass invariant (load-bearing)
//!
//! `provenance_view()` performs ONE unmask pass per layer and feeds the
//! SAME clear bytes to both the display and the runtime fold. This is
//! structural, not incidental: the compiler may clone a referenced
//! constant into several `.rodata` copies across consumer functions, so
//! two passes (display in one call, integrity in another) could read
//! different copies — the night-signature-1 draft had exactly that hole,
//! found by patching real binaries (a forged display next to a green
//! status). One pass per call site closes it: whatever bytes the report
//! shows are exactly the bytes the fingerprint folds.
//!
//! # The black_box barrier (night-signature-1 hardening, retained)
//!
//! The unmask is a pure function of compile-time constants, so LLVM
//! would constant-fold a naive runtime recompute back into the embedded
//! digest — a patched artifact would still report `verified`. The words
//! and seeds therefore pass through `std::hint::black_box`: the fold
//! genuinely reads the artifact's bytes at runtime. Verified by
//! end-to-end tamper probes (a flipped byte in any masked word of the
//! built binary flips the status).
//!
//! # Identity binding between the layers
//!
//! The manifest carries "Official Build by <identity> <year>"; the
//! authors string starts with the same identity. The runtime extracts
//! the identity core from the materialized manifest (everything after
//! the marker, minus the year suffix) and requires the authors string
//! to start with it. Patching one layer alone breaks the binding;
//! patching both consistently requires regenerating the masked words
//! AND the fingerprints — at which point the attacker has fully
//! understood the system (see the honest limits below).
//!
//! # Threat model (honest limits)
//!
//! This is provenance marking and tamper evidence, not DRM, and it does
//! not resist memory forensics: once `-V` materializes the plaintext,
//! the string lives in process memory and a determined attacker can
//! extract it from there. The defense targets the lazy grep-and-strip
//! rebrand (the owner's stated threat): the artifact carries no
//! greppable mark, so a thief cannot find what to remove, and a source
//! rebrand that rewrites the visible branding still ships constants it
//! does not recognize — their build keeps materializing the original
//! owner. A determined attacker with full understanding of this module
//! can regenerate everything; the legal layer (NOTICE, TRADEMARK.md,
//! AGPL) is the backstop. The constants are generated by
//! `scripts/release/generate-provenance-words.py` — the committed truth
//! source, which also carries the identity in plaintext by design, the
//! same way NOTICE does.

// --- Mask machinery (const, shared by compile-time and runtime) ------

/// FNV-1a 64-bit offset basis.
const FNV1A64_OFFSET_BASIS: u64 = 0xcbf2_9ce4_8422_2325;
/// FNV-1a 64-bit prime.
const FNV1A64_PRIME: u64 = 0x0000_0100_0000_01b3;

/// Golden-ratio increment (splitmix64's additive constant).
const SPLITMIX64_GOLDEN: u64 = 0x9e37_79b9_7f4a_7c15;

/// One splitmix64 round (Zinkst et al.), used to derive the per-word
/// masks. Written as a `const fn` with wrapping arithmetic so the same
/// implementation serves the compile-time fingerprints and the runtime
/// unmask — one implementation, no drift. Byte-exact mirror lives in
/// `scripts/release/generate-provenance-words.py`; changing one side
/// requires changing both and re-running the generator.
const fn splitmix64_mix(z: u64) -> u64 {
    let a = z.wrapping_add(SPLITMIX64_GOLDEN);
    let b = (a ^ (a >> 30)).wrapping_mul(0xbf58_476d_1ce4_e5b9);
    let c = (b ^ (b >> 27)).wrapping_mul(0x94d0_49bb_1331_11eb);
    c ^ (c >> 31)
}

/// Mask stream for word `index`: mix(seed + (index + 1) * GOLDEN).
///
/// Index-addressable (no sequential state to mirror), deterministic,
/// and different per layer because the seeds differ.
const fn mask_for(seed: u64, index: usize) -> u64 {
    splitmix64_mix(seed.wrapping_add(SPLITMIX64_GOLDEN.wrapping_mul(index as u64 + 1)))
}

// --- Layer D0: masked manifest words ---------------------------------
//
// Generated by scripts/release/generate-provenance-words.py. Do not
// hand-edit: rotate via the generator (edit the truth strings there,
// re-run, paste). The words encode the full Signature-line manifest in
// UTF-8, chunked little-endian, XOR-masked word-by-word.

pub(crate) const MANIFEST_SEED: u64 = 0x9D3A7C1E44B26F08;
pub(crate) const MANIFEST_BYTE_LEN: usize = 64; // 8 words
const MASKED_MANIFEST_WORDS: [u64; 8] = [
    0x3B9DF5DE357BBD4C,
    0xCAC7044006E3107F,
    0xD2ECB5D9EBDFC13E,
    0x6882A4D35ADE0996,
    0xBD5A530A02A69C79,
    0x4D988EF7EA40CDEA,
    0xFA20BBA8C6387500,
    0x86A6238CF9AE4161,
];

/// D2 digest over the clear manifest bytes, evaluated by the compiler.
///
/// The const eval unmasks the words and folds the clear bytes directly —
/// the plaintext manifest never exists as a literal in this module, so
/// it cannot leak into `.rodata` through this computation.
const MANIFEST_FINGERPRINT: u64 =
    layer_fingerprint(&MASKED_MANIFEST_WORDS, MANIFEST_SEED, MANIFEST_BYTE_LEN);

// --- Layer D1: masked authors words -----------------------------------
//
// Generated by scripts/release/generate-provenance-words.py (same law as
// D0). Encodes the Copyright-line authors string under an independent
// seed, so the identity has a second, differently-masked reconstruction
// inside the same artifact.

pub(crate) const AUTHORS_SEED: u64 = 0x1F4E6B8AC27D53A1;
pub(crate) const AUTHORS_BYTE_LEN: usize = 57; // 8 words
const MASKED_AUTHORS_WORDS: [u64; 8] = [
    0xFA61D696DEE608A9,
    0x3A18CA644CBD1F74,
    0x696AD9B99FE49F3C,
    0x07C6D1800BABEA97,
    0x2BC8AE1EC224C585,
    0xF6F90CBCC985CCDC,
    0x33CEC5F5656056B1,
    0x7D60B7BE7D37F069,
];

/// D2 digest over the clear authors bytes (same law as D0).
const AUTHORS_FINGERPRINT: u64 =
    layer_fingerprint(&MASKED_AUTHORS_WORDS, AUTHORS_SEED, AUTHORS_BYTE_LEN);

// --- Compile-time fold ------------------------------------------------

/// Const-evaluable digest of a masked layer: unmask word-by-word and
/// fold the clear bytes (up to `byte_len`, so zero padding never
/// participates) into the running FNV-1a 64-bit digest.
///
/// Input order and padding treatment are part of the contract — the
/// runtime recompute must traverse the identical byte stream.
const fn layer_fingerprint(words: &[u64], seed: u64, byte_len: usize) -> u64 {
    let mut hash = FNV1A64_OFFSET_BASIS;
    let mut emitted = 0usize;
    let mut i = 0usize;
    while i < words.len() {
        let clear = words[i] ^ mask_for(seed, i);
        let bytes = clear.to_le_bytes();
        let mut b = 0usize;
        while b < 8 && emitted < byte_len {
            hash ^= bytes[b] as u64;
            hash = hash.wrapping_mul(FNV1A64_PRIME);
            b += 1;
            emitted += 1;
        }
        i += 1;
    }
    hash
}

// --- Runtime materialization ------------------------------------------

/// Unmask a layer's words into clear bytes (zero-padded words truncated
/// to `byte_len`).
///
/// Callers pass the words and seed through `black_box` (see the
/// single-pass invariant in `provenance_view`): the unmask then reads
/// the artifact's real bytes and cannot be constant-folded.
fn unmask_to_bytes(words: &[u64], seed: u64, byte_len: usize) -> Vec<u8> {
    let mut out = Vec::with_capacity(words.len() * 8);
    for (i, word) in words.iter().enumerate() {
        let clear = *word ^ mask_for(seed, i);
        out.extend_from_slice(&clear.to_le_bytes());
    }
    out.truncate(byte_len);
    out
}

/// Runtime FNV-1a 64-bit fold over clear bytes (mirror of the const
/// fold's byte stream; used only on bytes already produced by one
/// unmask pass, never on fresh constant inputs, so there is nothing
/// here for LLVM to fold away).
fn fnv1a64_bytes(bytes: &[u8]) -> u64 {
    let mut hash = FNV1A64_OFFSET_BASIS;
    for byte in bytes {
        hash ^= *byte as u64;
        hash = hash.wrapping_mul(FNV1A64_PRIME);
    }
    hash
}

// --- Identity binding -------------------------------------------------

/// Marker that separates the manifest's brand prose from the owner
/// identity. Plaintext is safe here: it contains no identity, and its
/// bytes are inside the manifest, hence bound by `MANIFEST_FINGERPRINT`.
const MANIFEST_IDENTITY_MARKER: &str = "Official Build by ";

/// Year suffix the manifest carries after the identity. Generic text,
/// same binding rationale as the marker.
const MANIFEST_IDENTITY_YEAR: &str = " 2026";

/// Extract the owner identity core from a materialized manifest:
/// everything after the marker, minus the trailing year.
///
/// `None` means the manifest no longer carries the marker/year shape —
/// a tampering signal, not a panic path.
fn identity_core(manifest: &str) -> Option<&str> {
    manifest
        .split_once(MANIFEST_IDENTITY_MARKER)
        .map(|(_, tail)| tail)
        .and_then(|tail| tail.strip_suffix(MANIFEST_IDENTITY_YEAR))
}

// --- Version-report surface -------------------------------------------

/// Everything the `-V/--version` report renders from the provenance
/// layers: the Signature-line manifest, the Depth-matrix status line,
/// and the Copyright-line authors string.
///
/// All three derive from ONE unmask pass per layer inside
/// `provenance_view` — the single-pass invariant. `info::version_report`
/// must not unmask anything itself; it renders these fields verbatim.
pub(crate) struct ProvenanceView {
    /// Full manifest text for the `Signature:` line.
    pub manifest: String,
    /// `Depth-matrix:` line body (fingerprint + status + layers).
    pub depth_line: String,
    /// Authors text for the `Copyright:` line.
    pub authors: String,
}

/// Materialize the provenance layers and verify them, in one pass.
///
/// Verification is two-fold and both halves must hold for
/// `status=verified`:
///
/// 1. Fingerprint: the runtime fold over the clear bytes equals the
///    embedded const digest for BOTH layers. Catches any patched word.
/// 2. Binding: the identity core extracted from the manifest is a
///    prefix of the authors string. Catches incoherent single-layer
///    rebrands (the identity claims disagree).
///
/// Tampered bytes may not decode as UTF-8; `from_utf8_lossy` renders
/// replacement characters instead of panicking — the status line is the
/// honest signal, and a broken identity display next to `tampered` is
/// itself evidence.
#[must_use]
pub(crate) fn provenance_view() -> ProvenanceView {
    use std::hint::black_box;

    // One opaque read per layer: the words and seeds pass through
    // black_box, so the unmask below runs for real and every consumer
    // of `manifest` / `authors` downstream sees exactly these bytes.
    let manifest_bytes = unmask_to_bytes(
        black_box(&MASKED_MANIFEST_WORDS),
        black_box(MANIFEST_SEED),
        MANIFEST_BYTE_LEN,
    );
    let authors_bytes = unmask_to_bytes(
        black_box(&MASKED_AUTHORS_WORDS),
        black_box(AUTHORS_SEED),
        AUTHORS_BYTE_LEN,
    );

    let manifest_fp = fnv1a64_bytes(&manifest_bytes);
    let authors_fp = fnv1a64_bytes(&authors_bytes);
    let fingerprints_ok = manifest_fp == MANIFEST_FINGERPRINT && authors_fp == AUTHORS_FINGERPRINT;

    let manifest = String::from_utf8_lossy(&manifest_bytes).into_owned();
    let authors = String::from_utf8_lossy(&authors_bytes).into_owned();

    let binding_ok = identity_core(&manifest).is_some_and(|core| authors.starts_with(core));

    let status = if fingerprints_ok && binding_ok {
        "verified"
    } else {
        "tampered"
    };
    let depth_line = format!(
        "Depth-matrix: fp={MANIFEST_FINGERPRINT:016x} status={status} layers=d0:masked-words,d1:masked-words,d2:dual-fingerprint"
    );

    ProvenanceView {
        manifest,
        depth_line,
        authors,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Test oracles: the exact plaintext truths the masked words must
    /// materialize. These literals live ONLY in the test build — they
    /// are the one legitimate plaintext carrier in the module, because
    /// a test that cannot name its expected output proves nothing.
    /// The release artifact contains none of them (cfg(test) is
    /// stripped from the binary).
    const MANIFEST_ORACLE: &str = "Cosmic Dragon — Official Build by rezky_nightky (oxyzenQ) 2026";
    const AUTHORS_ORACLE: &str = "rezky_nightky (oxyzenQ) <with dot rezky at gmail dot com>";
    /// Generator cross-check values (scripts/release/
    /// generate-provenance-words.py prints them). If these diverge from
    /// the const eval, the generator and the Rust mirror have drifted.
    const MANIFEST_FINGERPRINT_ORACLE: u64 = 0xFE0D_7239_F86E_7C1B;
    const AUTHORS_FINGERPRINT_ORACLE: u64 = 0xC97B_13F8_1603_5D55;

    #[test]
    fn layers_materialize_to_oracles() {
        let view = provenance_view();
        assert_eq!(view.manifest, MANIFEST_ORACLE);
        assert_eq!(view.authors, AUTHORS_ORACLE);
    }

    #[test]
    fn masked_words_are_strings_invisible() {
        // The at-rest invisibility contract, pinned mechanically:
        // strings(1) reports runs of four or more printable ASCII bytes.
        // Every byte of every masked word (both layers) must stay below
        // that floor, so a thief's grep over the artifact finds nothing.
        for words in [&MASKED_MANIFEST_WORDS, &MASKED_AUTHORS_WORDS] {
            for word in words.iter() {
                let bytes = word.to_le_bytes();
                let mut run = 0usize;
                for byte in bytes {
                    if (0x20..=0x7E).contains(&byte) {
                        run += 1;
                        assert!(run < 4, "masked word {word:#x} leaks an ASCII run");
                    } else {
                        run = 0;
                    }
                }
            }
        }
    }

    #[test]
    fn const_fingerprints_match_generator_oracles() {
        // The generator's printed cross-check values must equal the
        // Rust const eval — otherwise the Python mask mirror and the
        // Rust const mirror have drifted and the block is corrupt.
        assert_eq!(MANIFEST_FINGERPRINT, MANIFEST_FINGERPRINT_ORACLE);
        assert_eq!(AUTHORS_FINGERPRINT, AUTHORS_FINGERPRINT_ORACLE);
    }

    #[test]
    fn const_fingerprints_match_runtime_fold() {
        // Same traversal contract, checked end-to-end: const eval over
        // the words == runtime fold over the materialized bytes.
        let manifest_fp = fnv1a64_bytes(&unmask_to_bytes(
            &MASKED_MANIFEST_WORDS,
            MANIFEST_SEED,
            MANIFEST_BYTE_LEN,
        ));
        let authors_fp = fnv1a64_bytes(&unmask_to_bytes(
            &MASKED_AUTHORS_WORDS,
            AUTHORS_SEED,
            AUTHORS_BYTE_LEN,
        ));
        assert_eq!(manifest_fp, MANIFEST_FINGERPRINT);
        assert_eq!(authors_fp, AUTHORS_FINGERPRINT);
    }

    #[test]
    fn tampered_words_break_the_fingerprint() {
        // Post-compile patching simulation: flipping one bit in any
        // masked word must change the digest — the fingerprint binds
        // the data it claims to protect.
        let mut tampered = MASKED_MANIFEST_WORDS;
        tampered[3] ^= 0x1;
        assert_ne!(
            layer_fingerprint(&tampered, MANIFEST_SEED, MANIFEST_BYTE_LEN),
            MANIFEST_FINGERPRINT,
            "patching a D0 word must break the fingerprint"
        );
        let mut tampered_authors = MASKED_AUTHORS_WORDS;
        tampered_authors[2] ^= 0x80;
        assert_ne!(
            layer_fingerprint(&tampered_authors, AUTHORS_SEED, AUTHORS_BYTE_LEN),
            AUTHORS_FINGERPRINT,
            "patching a D1 word must break the fingerprint"
        );
    }

    #[test]
    fn identity_core_extraction_and_binding() {
        let core = identity_core(MANIFEST_ORACLE).expect("marker present");
        assert_eq!(core, "rezky_nightky (oxyzenQ)");
        assert!(AUTHORS_ORACLE.starts_with(core), "layers bind coherently");
        // A rebranded manifest (different identity) breaks the binding:
        // the authors string no longer starts with the extracted core.
        let forged = "Cosmic Dragon — Official Build by someone_else 2026";
        let forged_core = identity_core(forged).expect("marker present");
        assert!(!AUTHORS_ORACLE.starts_with(forged_core));
        // Missing marker or missing year are tampering signals.
        assert!(identity_core("Cosmic Dragon").is_none());
        assert!(identity_core("Official Build by rezky_nightky").is_none());
    }

    #[test]
    fn provenance_view_shape_is_stable() {
        let view = provenance_view();
        assert!(
            view.manifest.starts_with("Cosmic Dragon — "),
            "manifest is the D0 display: {}",
            view.manifest
        );
        assert!(
            view.manifest.ends_with("rezky_nightky (oxyzenQ) 2026"),
            "manifest ends with the owner identity"
        );
        let depth = &view.depth_line;
        assert!(depth.starts_with("Depth-matrix: fp="), "depth line shape");
        assert!(
            depth.contains(" status=verified "),
            "pristine build reports verified"
        );
        assert!(
            depth.contains("layers=d0:masked-words,d1:masked-words,d2:dual-fingerprint"),
            "layers token describes the masked scheme"
        );
        let fp = depth
            .split(" status=")
            .next()
            .and_then(|head| head.strip_prefix("Depth-matrix: fp="))
            .expect("fp= token present");
        assert_eq!(fp.len(), 16);
        assert!(
            fp.chars()
                .all(|c| c.is_ascii_hexdigit() && !c.is_ascii_uppercase())
        );
    }
}
